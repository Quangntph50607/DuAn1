    private void showDataTable(List<MauSac> lists) {
        dtm = (DefaultTableModel) tbl_MauSac.getModel();
        dtm.setRowCount(0);
        AtomicInteger index = new AtomicInteger(1);
        lists.forEach(s -> dtm.addRow(new Object[]{
            index.getAndIncrement(), s.getMa_mau(), s.getTen_mau(), s.getTrang_thai() == 1 ? "Đang kinh doanh" : "Ngưng kinh doanh"
        }));
    }

    public void detail(int index) {
        MauSac ms = repo.getAll().get(index);
        txt_MaMau.setText(ms.getMa_mau());
        txt_TenMau.setText(ms.getTen_mau());
        if (ms.getTrang_thai() == 0) {
            rdo_NHD.setSelected(true);
        } else {
            rdo_DHD.setSelected(true);
        }
    }

    public MauSac getDataToForm() {
        MauSac ms = new MauSac();
        ms.setMa_mau(ma_mau);
        ms.setTen_mau(txt_TenMau.getText());
        ms.setTrang_thai(rdo_DHD.isSelected() ? 1 : 0);
        return ms;
    }

    private Boolean kiemTra_MS() {
        if (txt_TenMau.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Bạn chưa nhập vào màu sắc");
            txt_TenMau.requestFocus();
            return false;
        } else {
            return true;
        }
    }

